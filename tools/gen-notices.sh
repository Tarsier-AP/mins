#!/usr/bin/env bash
# Render THIRD_PARTY_NOTICES.md from tools/licenses/inventory.tsv.
#
#   bash tools/gen-notices.sh            # rewrite the notices
#   bash tools/gen-notices.sh --check    # fail if the file is stale
#   bash tools/gen-notices.sh --stdout   # print instead of writing
#
# The inventory is the single source of truth for component versions,
# licenses, link sets, and license files. tools/check-licenses.sh calls this
# with --check, so a stale notice or a missing license text fails the release.
set -euo pipefail

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
# shellcheck source=versions.env
source "$root/tools/versions.env"

mode=write
case "${1:-}" in
  --check) mode=check ;;
  --stdout) mode=stdout ;;
  "") ;;
  *) echo "usage: $0 [--check|--stdout]" >&2; exit 2 ;;
esac

inventory=$root/tools/licenses/inventory.tsv
out=$root/THIRD_PARTY_NOTICES.md
tools_file=$root/tools/bundle-tools.txt
[[ -f $inventory ]] || { echo "gen-notices: missing $inventory" >&2; exit 1; }
[[ -f $tools_file ]] || { echo "gen-notices: missing $tools_file" >&2; exit 1; }

trim() { sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' <<<"$1"; }

# Resolve ${VAR} against tools/versions.env. Unknown variables are a hard
# error: a typo in the inventory must not silently produce an empty version.
subst_version() {
  local v=$1 var
  while [[ $v =~ \$\{([A-Za-z_][A-Za-z0-9_]*)\} ]]; do
    var=${BASH_REMATCH[1]}
    if [[ -z ${!var+x} ]]; then
      echo "gen-notices: inventory references undefined version variable: $var" >&2
      return 1
    fi
    v=${v//\$\{$var\}/${!var}}
  done
  printf '%s' "$v"
}

# Markdown-safe inline code: license texts and versions contain no pipes, but
# guard the table cells anyway.
cell() { sed -e 's/|/\\|/g' <<<"$1"; }

# License identifiers in an SPDX expression: strip parentheses, split on
# AND/OR/WITH, trim. The `+` and hyphen characters are part of the id.
spdx_ids() {
  local expr
  expr=$(sed -E 's/[()]//g; s/ (AND|OR|WITH) /,/g' <<<"$1")
  local IFS=','
  local part
  for part in $expr; do
    part=$(trim "$part")
    [[ -n $part ]] && printf '%s\n' "$part"
  done
}

have() {
  local needle=$1 list=$2 item
  while IFS= read -r item; do
    [[ $item == "$needle" ]] && return 0
  done <<<"$list"
  return 1
}

add_unique() {
  local list=$1 item=$2
  if [[ -z $list ]]; then
    printf '%s' "$item"
  elif have "$item" "$list"; then
    printf '%s' "$list"
  else
    printf '%s\n%s' "$list" "$item"
  fi
}

# ---- load the inventory ----------------------------------------------------
ids=(); names=(); versions=(); spdxes=(); binaries=(); sources=()
copyrights=(); license_files=(); modifications=(); notes=()
lineno=0
while IFS=$'\t' read -r c_id c_name c_version c_spdx c_binaries c_source c_copyright c_license_files c_modifications c_notes; do
  lineno=$((lineno + 1))
  case "$c_id" in ''|'#'*) continue ;; esac
  if [[ -z ${c_notes+x} || -z $c_version || -z $c_spdx ]]; then
    echo "gen-notices: $inventory:$lineno: expected 10 tab-separated columns" >&2
    exit 1
  fi
  c_version=$(subst_version "$c_version")
  ids+=("$c_id")
  names+=("$c_name")
  versions+=("$c_version")
  spdxes+=("$c_spdx")
  binaries+=("$c_binaries")
  sources+=("$c_source")
  copyrights+=("$c_copyright")
  license_files+=("$c_license_files")
  modifications+=("$c_modifications")
  notes+=("$c_notes")
done <"$inventory"

[[ ${#ids[@]} -gt 0 ]] || { echo "gen-notices: inventory is empty" >&2; exit 1; }

# Every license file referenced by the inventory must exist. Build the
# deduplicated appendix list at the same time.
appendix=''
i=0
while [[ $i -lt ${#ids[@]} ]]; do
  files=${license_files[$i]}
  IFS=';' read -r -a flist <<<"$files"
  for f in "${flist[@]}"; do
    f=$(trim "$f")
    [[ -n $f ]] || continue
    [[ -f $root/$f ]] || {
      echo "gen-notices: ${ids[$i]} references missing license file: $f" >&2
      exit 1
    }
    appendix=$(add_unique "$appendix" "$f")
  done
  while IFS= read -r lic; do
    [[ -n $lic ]] || continue
    f="LICENSES/$lic.txt"
    [[ -f $root/$f ]] || {
      echo "gen-notices: ${ids[$i]} uses SPDX id $lic but $f is missing" >&2
      exit 1
    }
    appendix=$(add_unique "$appendix" "$f")
  done < <(spdx_ids "${spdxes[$i]}")
  i=$((i + 1))
done
appendix=$(printf '%s\n' "$appendix" | sort -u)

# ---- render ---------------------------------------------------------------
render() {
  cat <<'EOF'
# Third-party notices

<!-- Generated by tools/gen-notices.sh from tools/licenses/inventory.tsv. -->
<!-- Do not edit this file by hand: run `make licenses` to regenerate it. -->

`mins` itself is licensed under the MIT License (see `LICENSE`). It embeds
compressed copies of the media tools listed below and extracts them to a cache
directory at runtime. Those tools are separate programs: `mins` invokes them
with command-line arguments and communicates through pipes and files. It does
not link against them.

This file records the components actually shipped in a release, their
licenses, and the license texts that apply. It is a factual notice, not legal
advice. Every release also contains a `LICENSES/` directory with the full
texts, and publishes a sources archive (see "LGPL compliance" below).

## Components

| component | version | license | embedded in | source |
|---|---|---|---|---|
EOF

  i=0
  while [[ $i -lt ${#ids[@]} ]]; do
    local bin_list=${binaries[$i]//;/, }
    local src=${sources[$i]}
    cat <<EOF
| ${names[$i]} | $(cell "${versions[$i]}") | \`$(cell "${spdxes[$i]}")\` | $(cell "$bin_list") | <$src> |
EOF
    i=$((i + 1))
  done

  cat <<'EOF'

## Component details

EOF
  i=0
  while [[ $i -lt ${#ids[@]} ]]; do
    local text_list='' text_part
    IFS=';' read -r -a text_parts <<<"${license_files[$i]}"
    for text_part in "${text_parts[@]}"; do
      text_part=$(trim "$text_part")
      [[ -n $text_part ]] || continue
      if [[ -z $text_list ]]; then
        text_list="\`$text_part\`"
      else
        text_list="$text_list, \`$text_part\`"
      fi
    done
    cat <<EOF
### ${names[$i]} (\`${ids[$i]}\`)

- **Version:** ${versions[$i]}
- **License:** \`${spdxes[$i]}\`
- **Copyright:** ${copyrights[$i]}
- **Modifications:** ${modifications[$i]}
- **Notes:** ${notes[$i]}
- **License texts:** ${text_list}

EOF
    i=$((i + 1))
  done

  cat <<'EOF'
## What each shipped executable contains

The table lists the components whose code is statically linked into each
executable. System C/C++ runtime libraries (`libc`, `libm`, `libstdc++`, the
Windows system DLLs, and the macOS system libraries) are provided by the host
and are not redistributed.

| executable | components |
|---|---|
EOF

  # Preserve bundle-tools order, then mins last.
  local tool comp_list
  while IFS= read -r tool; do
    tool=$(trim "$tool")
    case "$tool" in ''|'#'*) continue ;; esac
    comp_list=''
    i=0
    while [[ $i -lt ${#ids[@]} ]]; do
      if have "$tool" "$(printf '%s' "${binaries[$i]}" | sed 's/;/\n/g')"; then
        if [[ -z $comp_list ]]; then
          comp_list=${names[$i]}
        else
          comp_list="$comp_list, ${names[$i]}"
        fi
      fi
      i=$((i + 1))
    done
    [[ -n $comp_list ]] || comp_list='(none recorded)'
    printf '| `%s` | %s |\n' "$tool" "$comp_list"
  done <"$tools_file"

  comp_list=''
  i=0
  while [[ $i -lt ${#ids[@]} ]]; do
    if have "mins" "$(printf '%s' "${binaries[$i]}" | sed 's/;/\n/g')"; then
      if [[ -z $comp_list ]]; then
        comp_list=${names[$i]}
      else
        comp_list="$comp_list, ${names[$i]}"
      fi
    fi
    i=$((i + 1))
  done
  printf '| `mins` | %s |\n' "$comp_list"

  cat <<'EOF'

## LGPL compliance

The following components are licensed under the GNU Lesser General Public
License and are statically linked into the executables shown above:

- **FFmpeg** (LGPL-2.1-or-later), in `ffmpeg` and `ffprobe`.
- **libheif** (LGPL-3.0-or-later), in `heif-convert` and `heif-info`.
- **libde265** (LGPL-3.0-or-later), in `heif-convert` and `heif-info`.

`mins` is not linked against these libraries. It runs the bundled programs as
separate processes. The MIT license for `mins` does not extend to them, and
their licenses do not extend to `mins`.

Each release publishes the complete corresponding source of every LGPL
library in `mins_<version>_sources.tar.xz`, together with the build scripts,
patches, pinned versions, and license texts. The target-specific archive
`mins_<version>_relink_<os>_<arch>.tar.xz` contains the static archives and
object files needed to relink `heif-convert` and `heif-info` against modified
versions of libheif or libde265, plus the exact link command and instructions.
FFmpeg is an LGPL work in its own right; the sources archive contains its
complete source and the scripts that rebuild it with `tools/build.sh`.

FFmpeg is configured without `--enable-gpl`, `--enable-nonfree`, and
`--enable-version3`. No GPL-only decoders, filters, or external GPL libraries
are enabled, and no non-free library is linked.

If you modify an LGPL library, the relink archive and the build scripts are
the materials you need. The sources archive's `SOURCES.md` gives the exact
commands.

## Full license texts

The same files are shipped in the release archive's `LICENSES/` directory.

EOF

  first=1
  while IFS= read -r f; do
    [[ -n $f ]] || continue
    if [[ $first == 1 ]]; then
      first=0
    else
      printf '\n'
    fi
    printf '### `%s`\n\n~~~~text\n' "$f"
    cat "$root/$f"
    # Guarantee a newline before the closing fence even if the file lacks one.
    if [[ -s $root/$f && $(tail -c 1 "$root/$f" | wc -l) -eq 0 ]]; then
      printf '\n'
    fi
    printf '~~~~\n'
  done <<<"$appendix"
}

tmp=$(mktemp "${TMPDIR:-/tmp}/mins-notices.XXXXXX")
trap 'rm -f "$tmp"' EXIT
render >"$tmp"

case $mode in
  stdout)
    cat "$tmp"
    ;;
  check)
    if ! cmp -s "$tmp" "$out"; then
      echo "gen-notices: $out is stale; regenerate it with 'make licenses'" >&2
      diff -u "$out" "$tmp" | sed -n '1,120p' >&2 || true
      exit 1
    fi
    echo "gen-notices: THIRD_PARTY_NOTICES.md is current"
    ;;
  write)
    mv "$tmp" "$out"
    echo "gen-notices: wrote $out"
    ;;
esac
